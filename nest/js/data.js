export function levelOf(love) {
  let i = 0; while (i < LEVELS.length - 1 && love >= LEVELS[i + 1][0]) i++;
  const cur = LEVELS[i][0], next = LEVELS[i + 1]?.[0];
  return { lv: i + 1, title: LEVELS[i][1], pct: next ? (love - cur) / (next - cur) : 1, next };
}
